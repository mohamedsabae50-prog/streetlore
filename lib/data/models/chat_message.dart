class ChatMessage {
  final String id;
  final String placeId;
  final String userId;
  final String userName;
  final String text;
  final DateTime sentAt;
  final String? userAvatarColor;

  const ChatMessage({
    required this.id,
    required this.placeId,
    required this.userId,
    required this.userName,
    required this.text,
    required this.sentAt,
    this.userAvatarColor,
  });

  /// Parses a row of `public.place_chat` (`id bigint`, `message text`,
  /// `user_id uuid`, `sent_at timestamptz`). `id` may arrive as an int
  /// (PostgREST / realtime) or a String (local optimistic messages), and the
  /// body column is `message` — `text` is accepted as a legacy fallback.
  factory ChatMessage.fromJson(Map<String, dynamic> json) => ChatMessage(
    id: json['id'].toString(),
    placeId: json['place_id'] as String,
    userId: (json['user_id'] as String?) ?? '',
    userName: (json['user_name'] as String?) ?? 'Explorer',
    text: (json['message'] ?? json['text']) as String,
    sentAt: json['sent_at'] == null
        ? DateTime.now()
        : DateTime.parse(json['sent_at'] as String),
    userAvatarColor: json['user_avatar_color'] as String?,
  );

  /// The insert payload for `public.place_chat`. `id` is generated by the
  /// database (`bigint generated always as identity`), `sent_at` defaults to
  /// `now()`, and the table has no avatar-colour column, so none of those are
  /// sent. `user_id` must equal `auth.uid()` for the insert RLS policy.
  Map<String, dynamic> toJson() => {
    'place_id': placeId,
    'user_id': userId,
    'user_name': userName,
    'message': text,
  };

  ChatMessage copyWith({String? text}) => ChatMessage(
    id: id,
    placeId: placeId,
    userId: userId,
    userName: userName,
    text: text ?? this.text,
    sentAt: sentAt,
    userAvatarColor: userAvatarColor,
  );
}
