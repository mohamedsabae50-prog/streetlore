PlaceModel _redSeaPlace(
  String id,
  String nameEn,
  String nameAr,
  double lat,
  double lng,
  String category,
  String categoryAr,
  String address,
  String addressAr,
  String openHours,
  String descriptionEn,
  String descriptionAr, {
  int? localPrice,
  int? foreignPrice,
  PriceLevel? priceLevel,
  String? priceNote,
  String? priceNoteAr,
}) {
  final imageUrl = redSeaImageUrls[id]!;
  final resolvedPriceLevel =
      priceLevel ??
      (localPrice == null
          ? PriceLevel.free
          : foreignPrice != null && foreignPrice > 500
          ? PriceLevel.expensive
          : PriceLevel.moderate);
  return PlaceModel(
    id: id,
    nameEn: nameEn,
    nameAr: nameAr,
    descriptionEn: descriptionEn,
    descriptionAr: descriptionAr,
    imageUrl: imageUrl,
    imageUrls: [imageUrl],
    rating: 4.5,
    category: category,
    categoryAr: categoryAr,
    lat: lat,
    lng: lng,
    address: '$address, Red Sea Governorate, Egypt',
    addressAr: '$addressAr، محافظة البحر الأحمر، مصر',
    governorate: 'red_sea',
    openHours: openHours,
    priceLevel: resolvedPriceLevel,
    priceNote: priceNote ?? (localPrice == null ? 'Free admission' : 'Adults'),
    priceNoteAr: priceNoteAr ?? (localPrice == null ? 'دخول مجاني' : 'للكبار'),
    priceLocalEgp:
        localPrice ?? (resolvedPriceLevel == PriceLevel.free ? 0 : null),
    priceForeignerEgp:
        foreignPrice ?? (resolvedPriceLevel == PriceLevel.free ? 0 : null),
  );
}
