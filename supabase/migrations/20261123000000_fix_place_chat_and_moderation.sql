-- Repair mixed legacy place IDs and add user-generated content moderation.

CREATE TABLE IF NOT EXISTS public.place_chat (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  place_id text NOT NULL,
  user_id uuid NOT NULL,
  user_name text NOT NULL DEFAULT 'Explorer',
  user_email text,
  avatar_url text,
  message text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  is_flagged boolean NOT NULL DEFAULT false,
  report_count integer NOT NULL DEFAULT 0
);

DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'place_chat'
      AND column_name = 'text'
  ) AND NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'place_chat'
      AND column_name = 'message'
  ) THEN
    ALTER TABLE public.place_chat RENAME COLUMN text TO message;
  ELSIF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'place_chat'
      AND column_name = 'text'
  ) AND EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'place_chat'
      AND column_name = 'message'
  ) THEN
    UPDATE public.place_chat
    SET message = coalesce(nullif(message, ''), text);
    ALTER TABLE public.place_chat DROP COLUMN text;
  END IF;
END;
$$;

ALTER TABLE public.place_chat
  ADD COLUMN IF NOT EXISTS id bigint GENERATED BY DEFAULT AS IDENTITY,
  ADD COLUMN IF NOT EXISTS place_id text,
  ADD COLUMN IF NOT EXISTS user_id uuid,
  ADD COLUMN IF NOT EXISTS user_name text NOT NULL DEFAULT 'Explorer',
  ADD COLUMN IF NOT EXISTS user_email text,
  ADD COLUMN IF NOT EXISTS avatar_url text,
  ADD COLUMN IF NOT EXISTS message text NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS created_at timestamptz NOT NULL DEFAULT now(),
  ADD COLUMN IF NOT EXISTS is_flagged boolean NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS report_count integer NOT NULL DEFAULT 0;

-- Fallback and seeded IDs need not exist in public.places.
DO $$
DECLARE
  constraint_row record;
BEGIN
  FOR constraint_row IN
    SELECT conname
    FROM pg_constraint
    WHERE conrelid = 'public.place_chat'::regclass
      AND contype = 'f'
      AND confrelid = 'public.places'::regclass
  LOOP
    EXECUTE format(
      'ALTER TABLE public.place_chat DROP CONSTRAINT %I',
      constraint_row.conname
    );
  END LOOP;
END;
$$;

ALTER TABLE public.place_chat
  ALTER COLUMN place_id TYPE text USING place_id::text;

DO $$
DECLARE
  id_type text;
BEGIN
  SELECT data_type INTO id_type
  FROM information_schema.columns
  WHERE table_schema = 'public'
    AND table_name = 'place_chat'
    AND column_name = 'id';
  IF id_type = 'text' THEN
    ALTER TABLE public.place_chat
      ALTER COLUMN id SET DEFAULT gen_random_uuid()::text;
  END IF;
END;
$$;

DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public'
      AND table_name = 'place_chat'
      AND column_name = 'sent_at'
  ) THEN
    EXECUTE 'UPDATE public.place_chat SET created_at = coalesce(sent_at, created_at)';
    EXECUTE 'ALTER TABLE public.place_chat ALTER COLUMN sent_at SET DEFAULT now()';
  END IF;
END;
$$;

