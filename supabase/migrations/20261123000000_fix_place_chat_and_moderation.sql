CREATE OR REPLACE FUNCTION public.streetlore_contains_profanity(value text)
RETURNS boolean
LANGUAGE plpgsql
IMMUTABLE
AS $$
DECLARE
  normalized text;
BEGIN
  normalized := lower(coalesce(value, ''));
  normalized := translate(normalized, 'أإآى', 'اااي');
  normalized := regexp_replace(normalized, '[[:punct:][:space:]]+', ' ', 'g');
  RETURN normalized
      ~ '(^| )(asshole|bastard|bitch|damn|fuck|fucker|shit|slut|whore)( |$)'
    OR normalized ~ '(احا|اخرس|حمار|خرا|شرموط|كس|كلب|منيوك|وسخ|ياحيوان)';
END;
$$;

CREATE OR REPLACE FUNCTION public.streetlore_reject_profanity()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  body text;
BEGIN
  IF TG_TABLE_NAME = 'place_chat' THEN
    body := NEW.message;
  ELSE
    body := NEW.comment;
  END IF;
  IF public.streetlore_contains_profanity(body) THEN
    RAISE EXCEPTION 'Content contains language that is not allowed.'
      USING ERRCODE = '22023';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS place_chat_profanity_guard ON public.place_chat;
CREATE TRIGGER place_chat_profanity_guard
  BEFORE INSERT OR UPDATE OF message ON public.place_chat
  FOR EACH ROW EXECUTE FUNCTION public.streetlore_reject_profanity();

DROP TRIGGER IF EXISTS reviews_profanity_guard ON public.reviews;
CREATE TRIGGER reviews_profanity_guard
  BEFORE INSERT OR UPDATE OF comment ON public.reviews
  FOR EACH ROW EXECUTE FUNCTION public.streetlore_reject_profanity();

CREATE OR REPLACE FUNCTION public.streetlore_apply_content_report()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NEW.target_type = 'chat' THEN
    UPDATE public.place_chat
    SET report_count = report_count + 1, is_flagged = true
    WHERE id::text = NEW.target_id;
  ELSE
    UPDATE public.reviews
    SET report_count = report_count + 1, is_flagged = true
    WHERE id::text = NEW.target_id;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS content_reports_apply_target ON public.content_reports;
CREATE TRIGGER content_reports_apply_target
  AFTER INSERT ON public.content_reports
  FOR EACH ROW EXECUTE FUNCTION public.streetlore_apply_content_report();

